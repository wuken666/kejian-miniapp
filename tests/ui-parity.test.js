const pageNames = ['home', 'schedule', 'students', 'record', 'feedback', 'profile', 'insights']
for (const pageName of pageNames) {
  const wxml = read(`pages/${pageName}/index.wxml`)
  const javascript = read(`pages/${pageName}/index.js`)
  const bindings = [...wxml.matchAll(/(?:bind|catch)(?:tap|input|change|confirm|longpress|scrolltolower)="([A-Za-z0-9_$]+)"/g)]
    .map((match) => match[1])
  for (const binding of new Set(bindings)) {
    const methodPattern = new RegExp(`^\\s{2}(?:async\\s+)?${binding}\\s*\\(`, 'm')
    assert.match(javascript, methodPattern, `${pageName} 缺少事件方法 ${binding}`)
  }
}
pass('所有页面点击与输入事件均有对应方法')

